#ifndef HUI_MCP_H
#define HUI_MCP_H

/* ============================================================================
 * HUI 主机命令 ↔ MCP 工具的桥 (一条命令一个工具)。
 *
 * 时机: 由 Board::PrepareBeforeConnect() 调用 —— 即 4G 已通、总线上电已稳定, 但
 * 协议还没连上的那一刻。为什么必须卡在这里: 实测后端在协议连上后约 190ms 就会问
 * tools/list, 而它不一定理会 notifications/tools/list_changed —— 晚于第一次
 * tools/list 注册的工具, 在 AI 眼里等于不存在 (这是本项目踩过的最贵的一个坑)。
 *
 * 流程 (只做一次, 读不到就本次放弃, 不重试):
 *   read 1000 (2s 超时) → 2 字节设备 ID → 从 flash 找 device_id 匹配的 JSON
 *   → 按手册里的每条命令生成一个 MCP 工具:
 *
 *     self.hui.<alias||host_<device_id>>.<语义名>
 *     例: self.hui.host1.set_headlight(on = true)
 *
 * 为什么不做成 3 个通用工具: 工具名 + JSON Schema 是大模型选命令/填参数的主要依据。
 * 具体工具能做到通用工具做不到的三件事:
 *   1. 参数类型/范围/长度由 Property 约束, 非法值在 DoToolCall 就被拦下 (-32602),
 *      根本到不了 CAN 总线 —— 车控场景最要紧的一条。
 *   2. 字节编码 (大端 / ioctl 前缀) 由固件按手册完成, AI 只说人话。
 *   3. 命令选择靠工具名, 不靠 AI 在一长串命令号里抄写 (抄错就是写错寄存器)。
 *
 * 注册完之后 tools_ 再不被改动, 所以整条路径**不需要任何锁**。
 * 手册只在 RAM 缓存, 不写 NVS。
 * ========================================================================= */

/**
 * @brief 按手册注册 self.hui.* 工具。幂等。
 *
 * 会阻塞 (最多约 2s 的 read 1000 超时) —— 调用方是激活任务, 此刻 OTA 与网络都已
 * 就绪, 只是还没连协议, 所以这点等待只推迟联网。
 */
void HuiMcp_Init(void);

#endif /* HUI_MCP_H */
